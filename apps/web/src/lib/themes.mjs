/** Тема по ключу; при неизвестном ключе — тема по умолчанию. */
export function getTheme(key) {
  return THEMES.find((t) => t.key === key) || THEMES.find((t) => t.key === DEFAULT_THEME);
}

/** Темы, сгруппированные для переключателя: сначала светлые, потом тёмные. */
