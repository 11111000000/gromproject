/**
 * Темы оформления ГРОМ — единый источник правды.
 *
 * Отсюда берутся:
 *   • CSS-переменные тем      — Base.astro генерирует <style> из THEMES
 *   • Переключатель в шапке   — Base.astro рендерит список из THEMES
 *   • meta theme-color        — по полю meta
 *   • Проверка контраста      — scripts/check-themes.mjs
 *
 * Контракт токенов (одинаков для всех тем, значения — свои):
 *
 *   Поверхности   bg, bg-alt, surface, surface-2, border, border-strong
 *   Текст         text, muted, heading
 *   Акцент        accent, accent-hover, accent-fg, accent-text, accent-border, accent-2
 *   Полоса        band-bg, band-fg, band-accent, band-border   (герой, PRO, отзывы, калькулятор)
 *   Шапка         header-bg, header-fg, header-accent
 *   Подвал        footer-bg, footer-fg, footer-accent
 *   Герой         hero-from, hero-to
 *   Текстура      texture-base, texture-ink, texture-glow, texture-opacity
 *   Прочее        glow, brand
 *
 * Правила:
 *   • accent        — заливка кнопок/бейджей; accent-fg — текст на ней
 *   • accent-text   — акцент как ТЕКСТ на светлой поверхности (затемнён, ≥4.5:1)
 *   • accent-border — акцент как ГРАНИЦА на светлой поверхности (≥3:1)
 *   • band-*        — инверсная полоса; в светлых темах она тоже светлая
 *   • brand         — фирменная молния, константа для всех тем
 */

